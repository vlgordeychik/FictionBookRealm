#pragma once
#include <string>

// ───────────────────────────────────────────────────────────────────────────
// Конфигурация ридера: settings.json (настройки) + state.json (состояние).
//
// Вся схема описана одной таблицей в config.cpp. Из неё же генерируется
// settings.json с пояснениями к каждому параметру, поэтому комментарии в файле
// не могут разойтись с кодом: диапазоны, значения по умолчанию и описания
// берутся из одного места.
//
// Запись ленивая: сеттеры только меняют значение в памяти и ставят флаг
// «грязно», а flush() раз за кадр пишет только изменившиеся файлы. Это не
// даёт всплесков тока на SD при каждом повороте страницы — на этом устройстве
// они уже приводили к brownout.
//
// Файл читается как JSONC: допускаются комментарии // и /* */ и висячая
// запятая. Любая ошибка разбора не приводит к падению — берутся значения по
// умолчанию.
// ───────────────────────────────────────────────────────────────────────────

namespace fs { class FileSystem; }

namespace cfg {

// Привязать ФС, прочитать оба файла, при отсутствии settings.json выполнить
// разовую миграцию из старого sims3.ini.
void init(fs::FileSystem* fs);

// ── Чтение. Значение по умолчанию берётся из схемы. ───────────────────────
std::string get_str(const char* key);
int         get_int(const char* key);
float       get_float(const char* key);

// ── Запись в память; файл будет перезаписан ближайшим flush(). ───────────
void set_str(const char* key, const char* value);
void set_int(const char* key, int value);
void set_float(const char* key, float value);

// Записать изменившиеся файлы. Вызывается раз за итерацию главного цикла,
// а также явно перед выключением и deep sleep.
void flush();

// ── Метаданные схемы (для UI и справки). ─────────────────────────────────
// Диапазоны значения; false, если ключ неизвестен или тип не числовой.
bool range_int(const char* key, int* lo, int* hi);
bool range_float(const char* key, float* lo, float* hi);
// Пояснение к параметру из таблицы схемы (nullptr, если ключ неизвестен).
const char* description(const char* key);

}  // namespace cfg
