#pragma once
#include <cstdint>
#include <string>

// Переносы внутри слова по простым орфографическим правилам.
//
// Точка разрыва допускается, только если с каждой стороны остаётся не меньше
// двух символов («нельзя переносить или оставлять на строке меньше двух
// символов»). Приоритет правил:
//
//   1. строго после ъ, ь, й;
//   2. Г-Г  — между двумя гласными, если это не первая и не последняя буква;
//   3. между двумя согласными — если слева остаётся слог (есть гласная) и ни
//      с одной стороны не образуется трёх согласных подряд. Среди подходящих
//      точек берётся та, у которой короче «хвост» из согласных, при равенстве
//      — самая правая. Даёт «сес-тра», «извес-тный», «свис-ток», «Мос-ква»;
//      отвергает «с-трана» (слева нет гласной) и «сест-ра» (хвост длиннее).
//
// Модуль ничего не знает про шрифт: ширины префиксов вычисляет вызывающий.
namespace hyph {

enum class Kind : uint8_t {
    Vowel,      // гласная
    Consonant,  // согласная
    Other,      // цифры, пунктуация, латиница и прочее
};

Kind classify(uint32_t cp);

// Декодирует UTF-8 строку. Возвращает число символов.
// out_offsets[i] — смещение i-го символа в байтах; в конце дописывается
// размер строки, т.е. массив имеет count+1 элементов. out_cps может быть
// nullptr, если нужны только смещения.
int decode_codepoints(const std::string& text, uint32_t* out_cps, int* out_offsets);

// Разрешена ли точка разрыва перед символом k (разрыв идёт между k-1 и k).
// Правило «минимум два символа с каждой стороны» проверяет вызывающий.
bool break_allowed(const uint32_t* cps, int count, int k);
//   prefix_w[k] — ширина первых k символов слова в пикселях, prefix_w[0] == 0
//   max_k      — верхняя граница k (вызывающий передаёт count-2, чтобы справа
//                осталось не меньше двух символов)
// Возвращает k или -1. Приоритет: сначала правило ъ/ь/й, затем Г-Г, затем
// между согласными; внутри правила — самая правая подходящая точка.
int find_break(const uint32_t* cps, int count, const int* prefix_w,
               int max_k, int avail_px, int hyphen_px);

// Знак переноса: короткое тире U+2010 с откатом на дефис U+002D, если глифа
// в шрифте нет (text_width() вернёт 0 и ширины разъедутся).
inline constexpr char kHyphenUtf8[]          = "\xE2\x80\x90";  // U+2010
inline constexpr char kHyphenFallbackUtf8[]   = "-";             // U+002D
inline const char* hyphen_char(bool have_glyph) {
    return have_glyph ? kHyphenUtf8 : kHyphenFallbackUtf8;
}

}  // namespace hyph
