#pragma once

// Время суток для интерфейса. Аппаратные часы (BM8563) есть только на
// устройстве, а рисовать «ЧЧ:ММ» нужно и в симуляторе — иначе геометрию
// хедера нечем проверять. Поэтому источник времени вынесен сюда:
//
//   1) если платформа отвечает (устройство — BM8563, win32 — система),
//      берём её;
//   2) иначе берём clock_minutes из настроек и двигаем по tick_ms() от
//      загрузки. Так часы работают даже с неисправным чипом, и выставить
//      время можно всегда.
//
// Вызывать clock_init() нужно один раз, после cfg::init().

void clock_init();

// true — время известно; hh/mm в пределах суток.
bool clock_now(int& hh, int& mm);

// Записать время суток. Если аппаратные часы есть — в них, и это же
// значение кладём в запасной источник; иначе только в запасной.
// Возвращает false, если время взять не откуда.
bool clock_set(int hh, int mm);
